/**
 * Shell integration scripts. A child process cannot change its parent shell, so each shell
 * gets a small hook: on every prompt it compares one line in ~/.secretmgr/version (built-ins only)
 * and calls secretmgr only when something changed. Agent shells are skipped on purpose
 * (CLAUDECODE is set there); agent commands get their variables from the PreToolUse hook instead.
 */

function posix(shell) {
  const split = shell === 'zsh' ? '${=__SM_BIN}' : '$__SM_BIN';
  const hook =
    shell === 'zsh'
      ? `autoload -Uz add-zsh-hook 2>/dev/null && add-zsh-hook precmd __secretmgr_sync`
      : `case ";\${PROMPT_COMMAND:-};" in *";__secretmgr_sync;"*) ;; *) PROMPT_COMMAND="__secretmgr_sync\${PROMPT_COMMAND:+;$PROMPT_COMMAND}" ;; esac`;
  return `# secretmgr ${shell} integration (generated by \`secretmgr install\`; safe to delete)
case $- in *i*) ;; *) return 0 2>/dev/null ;; esac
[ -n "\${CLAUDECODE:-}" ] && return 0
__SM_HOME="\${SECRETMGR_HOME:-$HOME/.secretmgr}"
__SM_BIN="\${SECRETMGR_BIN:-secretmgr}"
if [ -z "\${SECRETMGR_ENV+x}" ] && [ -r "$__SM_HOME/default-env" ]; then
  read -r SECRETMGR_ENV < "$__SM_HOME/default-env"
  if [ -n "$SECRETMGR_ENV" ]; then export SECRETMGR_ENV; else unset SECRETMGR_ENV; fi
fi
__secretmgr_sync() {
  [ -n "\${SECRETMGR_ENV:-}" ] || return 0
  local v=0 key="$SECRETMGR_ENV/\${SECRETMGR_GROUP:-}"
  [ -r "$__SM_HOME/version" ] && read -r v < "$__SM_HOME/version"
  if [ "$v" != "\${__SECRETMGR_V:-}" ] || [ "$key" != "\${__SECRETMGR_K:-}" ]; then
    __SECRETMGR_V="$v"; __SECRETMGR_K="$key"
    local out
    out="$(${split} env --shell ${shell} --env "$SECRETMGR_ENV" \${SECRETMGR_GROUP:+--group "$SECRETMGR_GROUP"})" && eval "$out"
  fi
}
secretmgr() {
  case "\${1:-}" in
    use)
      [ -n "\${2:-}" ] || { echo "usage: secretmgr use <env> [group]" >&2; return 2; }
      export SECRETMGR_ENV="$2"
      if [ -n "\${3:-}" ]; then export SECRETMGR_GROUP="$3"; fi
      __SECRETMGR_V=""; __secretmgr_sync ;;
    load) shift; secretmgr use "\${1:-\${SECRETMGR_ENV:-dev}}" "\${2:-}" ;;
    unload)
      eval "$(${split} env --shell ${shell} --unload)"
      unset SECRETMGR_ENV SECRETMGR_GROUP __SECRETMGR_V __SECRETMGR_K ;;
    *) command ${split} "$@" ;;
  esac
}
alias sm=secretmgr
${hook}
__secretmgr_sync
`;
}

function fish() {
  return `# secretmgr fish integration (generated by \`secretmgr install\`; safe to delete)
if status is-interactive; and test -z "$CLAUDECODE"
    set -g __sm_home (test -n "$SECRETMGR_HOME"; and echo $SECRETMGR_HOME; or echo $HOME/.secretmgr)
    set -g __sm_bin (test -n "$SECRETMGR_BIN"; and echo $SECRETMGR_BIN; or echo secretmgr)
    if not set -q SECRETMGR_ENV; and test -r $__sm_home/default-env
        read -l __sm_def < $__sm_home/default-env
        test -n "$__sm_def"; and set -gx SECRETMGR_ENV $__sm_def
    end
    function __secretmgr_sync --on-event fish_prompt
        test -n "$SECRETMGR_ENV"; or return 0
        set -l v 0
        test -r $__sm_home/version; and read v < $__sm_home/version
        set -l key "$SECRETMGR_ENV/$SECRETMGR_GROUP"
        if test "$v" != "$__SECRETMGR_V"; or test "$key" != "$__SECRETMGR_K"
            set -g __SECRETMGR_V $v
            set -g __SECRETMGR_K $key
            set -l grp
            test -n "$SECRETMGR_GROUP"; and set grp --group $SECRETMGR_GROUP
            command $__sm_bin env --shell fish --env $SECRETMGR_ENV $grp | source
        end
    end
    function secretmgr
        switch "$argv[1]"
            case use
                set -gx SECRETMGR_ENV $argv[2]
                test -n "$argv[3]"; and set -gx SECRETMGR_GROUP $argv[3]
                set -g __SECRETMGR_V ""
                __secretmgr_sync
            case load
                secretmgr use (test -n "$argv[2]"; and echo $argv[2]; or echo $SECRETMGR_ENV)
            case unload
                command $__sm_bin env --shell fish --unload | source
                set -e SECRETMGR_ENV SECRETMGR_GROUP __SECRETMGR_V __SECRETMGR_K
            case '*'
                command $__sm_bin $argv
        end
    end
    alias sm secretmgr
    __secretmgr_sync
end
`;
}

function pwsh() {
  return `# secretmgr PowerShell integration (generated by \`secretmgr install\`; safe to delete)
if ([Environment]::UserInteractive -and -not $env:CLAUDECODE) {
  $global:__SmHome = if ($env:SECRETMGR_HOME) { $env:SECRETMGR_HOME } else { Join-Path $HOME '.secretmgr' }
  $global:__SmBin = (Get-Command secretmgr -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1).Source
  if (-not $env:SECRETMGR_ENV -and (Test-Path "$global:__SmHome/default-env")) { $env:SECRETMGR_ENV = (Get-Content "$global:__SmHome/default-env" -TotalCount 1) }
  function global:__SecretmgrSync {
    if (-not $env:SECRETMGR_ENV) { return }
    $v = '0'; if (Test-Path "$global:__SmHome/version") { $v = (Get-Content "$global:__SmHome/version" -TotalCount 1) }
    $key = "$($env:SECRETMGR_ENV)/$($env:SECRETMGR_GROUP)"
    if ($v -ne $global:__SmV -or $key -ne $global:__SmK) {
      $global:__SmV = $v; $global:__SmK = $key
      $a = @('env','--shell','pwsh','--env',$env:SECRETMGR_ENV); if ($env:SECRETMGR_GROUP) { $a += @('--group',$env:SECRETMGR_GROUP) }
      & $global:__SmBin @a | Out-String | Invoke-Expression
    }
  }
  function global:secretmgr {
    switch ($args[0]) {
      'use' { $env:SECRETMGR_ENV = $args[1]; if ($args[2]) { $env:SECRETMGR_GROUP = $args[2] }; $global:__SmV = ''; __SecretmgrSync }
      'load' { secretmgr use $(if ($args[1]) { $args[1] } else { $env:SECRETMGR_ENV }) }
      'unload' { & $global:__SmBin env --shell pwsh --unload | Out-String | Invoke-Expression; Remove-Item Env:SECRETMGR_ENV,Env:SECRETMGR_GROUP -ErrorAction SilentlyContinue }
      default { & $global:__SmBin @args }
    }
  }
  Set-Alias -Name sm -Value secretmgr -Scope Global
  $global:__SmOrigPrompt = $function:prompt
  function global:prompt { __SecretmgrSync; & $global:__SmOrigPrompt }
  __SecretmgrSync
}
`;
}

/** cmd has no prompt hook: new windows load via AutoRun, and \`sm\` refreshes an open window. */
function cmdFiles(bin) {
  const run = bin || 'secretmgr';
  return {
    'autorun.cmd': `@echo off
if defined CLAUDECODE exit /b 0
doskey sm=call "%USERPROFILE%\\.secretmgr\\sm.cmd" $*
call "%USERPROFILE%\\.secretmgr\\sm.cmd" load >nul 2>&1
`,
    'sm.cmd': `@echo off
setlocal enabledelayedexpansion
set "SM_BIN=${run}"
set "SM_ENV=%SECRETMGR_ENV%"
if "%~1"=="use" set "SM_ENV=%~2"
if "%~1"=="load" if "%SM_ENV%"=="" if exist "%USERPROFILE%\\.secretmgr\\default-env" set /p SM_ENV=<"%USERPROFILE%\\.secretmgr\\default-env"
if "%~1"=="" set "SM_ENV=%SECRETMGR_ENV%"
set "SM_TMP=%TEMP%\\secretmgr-%RANDOM%.cmd"
if "%~1"=="unload" ( %SM_BIN% env --shell cmd --unload > "%SM_TMP%" ) else if defined SM_ENV ( %SM_BIN% env --shell cmd --env !SM_ENV! > "%SM_TMP%" ) else ( %SM_BIN% %* & exit /b )
endlocal & call "%SM_TMP%" & del "%SM_TMP%" 2>nul
`,
  };
}

export function initScript(shell) {
  if (shell === 'bash' || shell === 'zsh') return posix(shell);
  if (shell === 'fish') return fish();
  if (shell === 'pwsh') return pwsh();
  throw new Error(`No init script for ${shell}`);
}

export { cmdFiles };
